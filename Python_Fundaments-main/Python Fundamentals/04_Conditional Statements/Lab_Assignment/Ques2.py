# Practical Example 6: Write a Python program to check if a number is prime using if_else.

num=int(input("Enter Number: "))

temp=0
for prime in range (2,num/2):
    if num/temp :
       temp=temp+1
    elif temp==0:
      print("It Is A Prime Number!")
    else:
       print("It Is Not A Prime Number!")

